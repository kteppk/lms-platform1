const assert = require('node:assert/strict');
const fs = require('node:fs');

// Shared acceptance workflow for local fixtures and an explicitly authorized live smoke check.
module.exports = async function verifyAssessment({ teacher, student, other, createStudent, expireAttempt, stamp }) {
  const rpc = (page,action,data) => page.evaluate(([action,data]) => callFunction(action,data).then(data=>({data}),e=>({code:e.code})),[action,data]);
  const title = 'Ручная проверка '+stamp;
  const tab = (page,name) => page.getByRole('button',{name:new RegExp(name)}).click();
  await tab(teacher,'Тесты');
  await teacher.locator('#materialSubject').selectOption('');
  await teacher.locator('#testTitle').fill(title);
  await teacher.locator('#testTimer').fill('5');
  await teacher.locator('.q-text').fill('Выберите второй');
  for(const [i,text] of ['Один','Два','Три','Четыре'].entries()) await teacher.locator('.q-opt').nth(i).fill(text);
  await teacher.locator('.q-correct').fill('2');
  for(const type of ['text','photo']) {
    await teacher.getByRole('button',{name:'+ Добавить вопрос',exact:true}).click();
    const q=teacher.locator('.question-block').last();
    await q.locator('.q-text').fill(type==='text'?'Объясните ответ':'Приложите фото');
    await q.locator('.q-type').selectOption(type);
  }
  await teacher.getByRole('button',{name:'Сохранить тест',exact:true}).click();
  await teacher.getByRole('heading',{name:title,exact:true}).waitFor();
  const testId=(await rpc(teacher,'listTeacherTests')).data.find(t=>t.title===title).id;
  await tab(student,'Тесты');
  await student.locator('.item').filter({has:student.getByRole('heading',{name:title,exact:true})}).getByRole('button',{name:'Пройти тест'}).click();
  await student.getByRole('radio',{name:'Два',exact:true}).check();
  await student.getByRole('textbox',{name:'Ответ 2',exact:true}).fill('Сохранённый текстовый ответ');
  const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64');
  await student.getByLabel('Фото 3',{exact:true}).setInputFiles({name:'answer.png',mimeType:'image/png',buffer:png});
  await student.locator('#photo-status-2').filter({hasText:'Фото загружено'}).waitFor();
  await student.locator('#draftStatus').filter({hasText:'Ответы сохранены на сервере.'}).waitFor();
  const first=await student.evaluate(()=>({id:attempt.attemptId,expiresAt:attempt.expiresAt}));
  await student.reload();
  await student.getByRole('heading',{name:title,exact:true}).waitFor();
  assert.equal(await student.getByRole('radio',{name:'Два',exact:true}).isChecked(),true);
  assert.equal(await student.getByRole('textbox',{name:'Ответ 2',exact:true}).inputValue(),'Сохранённый текстовый ответ');
  assert.deepEqual(await student.evaluate(()=>({id:attempt.attemptId,expiresAt:attempt.expiresAt})),first);
  assert.equal((await rpc(student,'startStudentTest',{testId})).data.attemptId,first.id);
  assert.equal((await rpc(student,'saveStudentDraft',{attemptId:first.id,revision:0,answers:{0:0}})).code,'conflict');
  await student.route('**/functions/v1/lms',route => {
    if (route.request().postDataJSON()?.action === 'saveStudentDraft') return route.abort();
    return route.continue();
  });
  const recoveredText='Локальный черновик после сбоя сети';
  await student.getByRole('textbox',{name:'Ответ 2',exact:true}).fill(recoveredText);
  await student.locator('#draftStatus').filter({hasText:'Ответы не сохранены на сервере.'}).waitFor();
  await student.unroute('**/functions/v1/lms');
  await student.reload();
  await student.getByRole('heading',{name:title,exact:true}).waitFor();
  assert.equal(await student.getByRole('textbox',{name:'Ответ 2',exact:true}).inputValue(),recoveredText);
  await student.locator('#draftStatus').filter({hasText:'Ответы сохранены на сервере.'}).waitFor();
  console.log('PASS autosave, reload restoration, unchanged deadline, single active attempt and stale-write rejection');
  teacher.once('dialog',d=>d.accept());
  await teacher.locator('.item').filter({has:teacher.getByRole('heading',{name:title,exact:true})}).getByRole('button',{name:'В архив',exact:true}).click();
  await teacher.locator('.item').filter({has:teacher.getByRole('heading',{name:title,exact:true})}).getByText(/В архиве/).waitFor();
  const student2=await createStudent();
  assert.equal((await rpc(student2,'startStudentTest',{testId})).code,'not-found');
  await student.reload();
  await student.getByRole('heading',{name:title,exact:true}).waitFor();
  await student.getByRole('button',{name:'Завершить тест',exact:true}).click();
  await student.getByRole('heading',{name:'Работа отправлена',exact:true}).waitFor();
  const pending=await rpc(student,'getResult',{resultId:first.id});
  assert.equal(pending.data.status,'pending_review'); assert.equal(pending.data.percentage,null);
  assert.equal(Object.hasOwn(pending.data.questions[0],'correct'),false);
  assert.equal((await rpc(other,'getResult',{resultId:first.id})).code,'not-found');
  assert.equal((await rpc(student2,'getResult',{resultId:first.id})).code,'not-found');
  assert.equal((await rpc(student,'reviewResult',{resultId:first.id,revision:0,grades:{1:1,2:1}})).code,'permission-denied');
  console.log('PASS archive preserves running work; manual answers await review; other users cannot read or grade the work');
  await tab(teacher,'Результаты тестов');
  await teacher.locator('#resultTestSelect').selectOption(testId);
  await teacher.locator('#resultsHeading').filter({hasText:title}).waitFor();
  const row=teacher.locator('[data-result-id="'+first.id+'"]');
  await row.getByRole('button',{name:'Проверить',exact:true}).click();
  await teacher.getByText(recoveredText,{exact:true}).waitFor();
  await teacher.locator('img.review-photo').waitFor();
  assert.equal(await teacher.locator('img.review-photo').evaluate(async img=>{if(!img.complete)await new Promise(resolve=>{img.onload=resolve;img.onerror=resolve});return img.naturalWidth>0;}),true);
  await teacher.locator('.manual-score[data-index="1"]').selectOption('1');
  await teacher.locator('.manual-score[data-index="2"]').selectOption('0');
  await teacher.locator('#reviewFeedback').fill('Текст принят, фото нужно исправить.');
  await teacher.getByRole('button',{name:'Сохранить проверку',exact:true}).click();
  await teacher.locator('[data-result-id="'+first.id+'"] [data-label="Баллы"]').filter({hasText:'2 / 3'}).waitFor();
  assert.equal((await rpc(other,'reviewResult',{resultId:first.id,revision:1,grades:{1:1,2:1},feedback:''})).code,'not-found');
  assert.equal((await rpc(teacher,'reviewResult',{resultId:first.id,revision:0,grades:{1:1,2:1},feedback:''})).code,'conflict');
  await tab(student,'Мои результаты');
  await student.locator('#resultTestSelect').selectOption(testId);
  const result=student.locator('[data-result-id="'+first.id+'"]');
  await result.getByText('2 / 3',{exact:true}).waitFor();
  await result.getByRole('button',{name:'Посмотреть',exact:true}).click();
  await student.getByText('Текст принят, фото нужно исправить.',{exact:true}).waitFor();
  const download=teacher.waitForEvent('download');
  await teacher.getByRole('button',{name:'Скачать Excel (.xlsx)',exact:true}).click();
  const file=await download;
  const xlsx=fs.readFileSync(await file.path());
  assert.equal(xlsx.subarray(0,2).toString(),'PK');assert.ok(xlsx.toString('utf8').includes(title));
  assert.equal((await rpc(student2,'listResults')).data.rows.length,0);
  console.log('PASS per-test results table, signed photo, manual scores/comment, student history, XLSX export and review conflicts');
  if(expireAttempt) {
    const timed=(await rpc(teacher,'createTest',{title:'Истечение '+stamp,timer:1,questions:[{type:'choice',text:'Вопрос',options:['а','б','в','г'],correct:1}]})).data.id;
    const a=(await rpc(student,'startStudentTest',{testId:timed})).data;
    await rpc(student,'saveStudentDraft',{attemptId:a.attemptId,revision:0,answers:{0:1}});
    await expireAttempt(a.attemptId);
    const expired=(await rpc(student,'getStudentAttempt',{attemptId:a.attemptId})).data;
    assert.equal(expired.result.score,1); assert.equal(expired.result.status,'graded');
    console.log('PASS expired work finalizes its saved answers without a running browser');
  }
};
